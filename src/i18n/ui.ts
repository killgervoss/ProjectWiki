export function ui(lang: Lang) { return lang === 'mn' ? mn : en; }
export function withCount(template: string, count: number) { return template.replace('{count}', String(count)); }

// Keep language prefixes and the optional hosting base path in one place.
export function sitePath(path = '') {
  return `${import.meta.env.BASE_URL.replace(/\/$/, '')}/${path.replace(/^\/+/, '')}`;
}
export function localePath(lang: Lang, path = '') { return sitePath(`${lang}/${path.replace(/^\/+/, '')}`); }
export function topicPath(lang: Lang, topicKey: string) { return localePath(lang, `topics/${topicKey}/`); }
